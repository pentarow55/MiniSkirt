def build_items(items):
    content = []
    for item in items:
        t = item["type"]
        if t == "empty":
            content.append({"type": "empty"})
            continue
        if t == "header":
            h = {"text": key(item["key"], "Text"), "type": "header"}
            if "position" in item:
                h["position"] = item["position"]
            content.append(h)
            continue
        if t == "text":
            content.append({"text": key(item["key"], "Text"), "help": key(item["key"], "Help"), "type": "text"})
            continue
        e = {"id": item["id"], "text": key(item["key"], "Text"), "help": key(item["key"], "Help"), "type": t}
        if t == "toggle":
            e["valueOptions"] = {"sourceType": "ModSettingBool"}
        elif t == "stepper":
            e["valueOptions"] = {"options": [key(o, "Text") for o in item["options"]], "sourceType": "ModSettingInt"}
        elif t == "keymap":
            e["valueOptions"] = {"sourceType": "ModSettingInt"}
        else:
            e["valueOptions"] = {"min": item["min"], "max": item["max"], "step": item["step"], "formatString": item["fmt"], "sourceType": "ModSettingFloat"}
        content.append(e)
    return content


def build_config():
    pages = [
        {
            "pageDisplayName": key(page["key"], "Text"),
            "cursorFillMode": "topToBottom",
            "content": build_items(page["items"]),
        }
        for page in PAGES
    ]
    cfg = {
        "modName": "MiniSkirt",
        "displayName": "MiniSkirt",
        "minMcmVersion": 9,
        "cursorFillMode": "topToBottom",
        "content": build_items(PAGES[0]["items"]),
        "pages": pages,
    }
    p = ASSETS / "MCM/Config/MiniSkirt/config.json"
    p.write_text(json.dumps(cfg, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def build_translations():
    want = set()
    keys_order = []
    for page in PAGES:
        want.add(page["key"])
        keys_order.append(page["key"])
        for item in page["items"]:
            if item["type"] != "empty":
                want.add(item["key"])
                keys_order.append(item["key"])
                for opt in item.get("options", ()):
                    want.add(opt)
                    keys_order.append(opt)
    out = ASSETS / "Interface/Translations"
    out.mkdir(parents=True, exist_ok=True)
    for lang, d in T.items():
        assert set(d) == want, (lang, set(d) ^ want)
        lines = []
        for k in keys_order:
            v = d[k]
            if isinstance(v, str):
                lines.append(f"{key(k, 'Text')}\t{v}")
            else:
                lines.append(f"{key(k, 'Text')}\t{v[0]}")
                lines.append(f"{key(k, 'Help')}\t{v[1]}")
        for mk, mv in MENU_T[lang].items():
            lines.append(f"$MSK_{mk}\t{mv}")
        for s in lines:
            assert "\n" not in s and s.count("\t") == 1, s
        data = "\r\n".join(lines) + "\r\n"
        (out / f"MiniSkirt_{lang}.txt").write_bytes(b"\xff\xfe" + data.encode("utf-16-le"))


build_config()
